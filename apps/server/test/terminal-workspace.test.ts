import { homedir } from "node:os";
import { readFileSync, realpathSync } from "node:fs";
import path from "node:path";
import { describe, expect, it } from "vitest";
import { loadPty } from "../../../packages/tools/src/pty";
import { RunState, WorkspaceRoot } from "@socrates/tools";
import { home, models, runtime, server, SCRIPTED, tempDir } from "./helpers";

describe.skipIf(!loadPty())("persistent terminal workspace", () => {
  it("resolves explicit, project, selected, single allowed and home folders independently of access", async () => {
    const { rt } = await runtime(home());
    const one = tempDir(), two = tempDir(), three = tempDir();
    expect(rt.terminalFolder().cwd).toBe(realpathSync(homedir()));
    await rt.updateSettings({ access: { scope: "folders", folders: [one] } });
    expect(rt.terminalFolder().cwd).toBe(one);
    await rt.updateSettings({ access: { folders: [one, two] } });
    expect(rt.terminalFolder().cwd).toBe(realpathSync(homedir()));
    await rt.updateSettings({ access: { scope: "full" } });
    expect(rt.terminalFolder().cwd).toBe(realpathSync(homedir()));
    const selected = rt.store.createWorkspace("Selected", two);
    await rt.updateSettings({ workingFolder: selected.id });
    expect(rt.terminalFolder().cwd).toBe(two);
    const project = rt.store.createWorkspace("Project", one);
    const goal = rt.store.createGoal({ title: "Project", objective: "Test", workspaceId: project.id });
    expect(rt.terminalFolder(undefined, goal.number).cwd).toBe(one);
    expect(rt.terminalFolder(three, goal.number).cwd).toBe(three);
    expect(() => rt.terminalDirectory(rt.config.home)).toThrow("private data");
    expect(() => rt.terminalDirectory("relative")).toThrow("full path");
    expect(() => rt.terminalDirectory(path.join(three, "missing"))).toThrow("no longer available");
  });

  it("shares two user shells with both tools, isolates projects, preserves model rebuilds and restores stopped tabs", async () => {
    const config = home({ settings: SCRIPTED });
    const deps = models();
    const { rt, request, app } = await server(config, deps);
    const root = tempDir();
    const ws = rt.store.createWorkspace("Work", root);
    await rt.updateSettings({ workingFolder: ws.id, access: { scope: "folders", folders: [root], approvals: "auto" } });
    const goal = rt.store.createGoal({ title: "Work", objective: "Test", workspaceId: ws.id });
    const task = rt.store.createTask(goal.id, { title: "Test terminals", objective: "Test" });
    const user = rt.store.recordUserMessage("Test terminals");
    const turn = rt.store.bindTurn({ userEventId: user.id, taskId: task.id, route: "continue_current", gateArmed: false, workspaceConfidence: "high" });
    const scope = { binding: { goalId: goal.id, taskId: task.id, chatId: turn.chatId, turnId: turn.id }, workspace: WorkspaceRoot.open("Work", root), run: new RunState(), signal: new AbortController().signal };
    let callId = 0;
    const tool = async (name: string, input: unknown) => {
      const result = await rt.socrates!.runner.run({ id: `tool-${++callId}`, name, input }, scope);
      return { ...result, json: JSON.parse(result.content) };
    };
    const first = (await request("POST", "/api/terminals", { goal: goal.number, task: task.number, name: "Backend" })).json().id;
    const second = (await request("POST", "/api/terminals", { name: "Frontend" })).json().id;
    expect(first).toMatch(/^term-/); expect(second).not.toBe(first);
    const before = rt.terminalManager.sessions().map(s => s.session.proc!.pid);
    expect((await tool("terminal_control", { action: "list" })).json.terminals.map((s: { terminal: string }) => s.terminal)).toEqual(["Backend", "Frontend"]);
    expect((await tool("terminal_control", { action: "write", terminal: first, input: "printf 'BACKEND_OK\\n'", settle_ms: 300 })).isError).toBe(false);
    expect((await tool("terminal_control", { action: "read", terminal: first, cursor: "c0" })).json.output).toContain("BACKEND_OK");
    expect((await tool("terminal_control", { action: "screen", terminal: first })).json.screen.text).toContain("BACKEND_OK");
    const pair = rt.terminalManager.sessions().find(s => s.session.id === second)!;
    pair.supervisor.input(pair.session, "echo USER_OK\r");
    expect((await tool("terminal_control", { action: "write", terminal: second, input: "echo COLLISION" })).json.error.code).toBe("user_typing");
    expect((await tool("terminal", { command: "echo AGENT_READY; sleep 30", background: true, name: "Worker", ready: { pattern: "AGENT_READY" } })).isError).toBe(false);
    expect(rt.terminalManager.sessions()).toHaveLength(3);
    const other = tempDir();
    const outside = (await request("POST", "/api/terminals", { cwd: other, goal: goal.number, name: "Outside" })).json().id;
    expect((await tool("terminal_control", { action: "list" })).json.terminals).toEqual(expect.arrayContaining([expect.objectContaining({ terminal: "Outside", cwd_absolute: other })]));
    expect((await tool("terminal_control", { action: "write", terminal: outside, input: "echo NOT_ALLOWED" })).json.error.code).toBe("approval_denied");
    await request("POST", `/api/terminals/${outside}`, { action: "close" });
    const otherWorkspace = rt.store.createWorkspace("Other", other);
    const otherGoal = rt.store.createGoal({ title: "Other", objective: "Test isolation", workspaceId: otherWorkspace.id });
    const foreign = (await request("POST", "/api/terminals", { goal: otherGoal.number, name: "Backend" })).json().id;
    expect(foreign).toMatch(/^term-/);
    expect((await tool("terminal_control", { action: "read", terminal: foreign })).json.error.code).toBe("terminal_not_found");
    expect((await request("POST", `/api/terminals/${first}`, { action: "rename", name: "Frontend" })).statusCode).toBe(400);
    expect((await request("POST", `/api/terminals/${first}`, { action: "rename", name: "API" })).statusCode).toBe(200);
    await rt.updateSettings({ chat: { provider: "gemini", model: "replacement" } });
    expect(rt.terminalManager.sessions().slice(0, 2).map(s => s.session.proc!.pid)).toEqual(before);
    expect((await tool("terminal_control", { action: "list" })).json.terminals).toHaveLength(3);
    const restarted = await tool("terminal_control", { action: "restart", terminal: first });
    expect(restarted.isError).toBe(false);
    expect(restarted.json.session_id).not.toBe(first);
    expect((await request("POST", `/api/terminals/${restarted.json.session_id}`, { action: "close" })).statusCode).toBe(200);
    expect(pair.session.status).toBe("running");
    expect((await request("POST", "/api/terminals", { cwd: config.home })).statusCode).toBe(400);
    const serialized = readFileSync(path.join(config.home, "terminal-tabs.json"), "utf8");
    expect(serialized).not.toContain('"env"');
    const long = await tool("terminal", { command: "echo LONG_READY; sleep 2.1", name: "Visible" });
    expect(long.isError).toBe(false);
    const retained = rt.terminalManager.sessions().find(s => s.session.spec.name === "Visible")!;
    expect(retained.session.status).toBe("exited");
    await request("POST", `/api/terminals/${retained.session.id}`, { action: "close" });
    const runningPids = rt.terminalManager.sessions().filter(s => s.session.status === "running").map(s => s.session.proc!.pid!);
    await app.close(); await rt.close();
    for (const pid of runningPids) expect(() => process.kill(pid, 0)).toThrow();
    const { rt: reopened } = await runtime(config, deps);
    expect(reopened.terminalManager.sessions().length).toBe(3);
    expect(reopened.terminalManager.sessions().every(s => s.session.status === "exited" && s.session.proc === null)).toBe(true);
    const restored = reopened.terminalManager.sessions().find(s => s.session.id === second)!;
    const next = await restored.supervisor.restart(restored.session);
    expect(next.proc?.pty).toBe(true);
    expect(next.spec.cwd).toBe(root);
    await reopened.terminalManager.close();
    const saved = readFileSync(path.join(config.home, "terminal-tabs.json"), "utf8");
    await reopened.terminalManager.close();
    expect(readFileSync(path.join(config.home, "terminal-tabs.json"), "utf8")).toBe(saved);
  }, 30_000);
});
